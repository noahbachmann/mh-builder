/**
 * Turns the MHW_Icons_SVG set (MIT, OthelloRhin) into one Vue component per icon under
 * `src/assets/icons/<icon id>.vue` (SVGO-optimized, rendered inline, no asset URLs).
 * Pinned to one commit like the data import; `src/icons.ts` lazy-loads them by id.
 *
 *   pnpm icons:import
 */
import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { optimize } from 'svgo'
import { WEAPON_TYPES, type WeaponType } from '../../src/data/types.ts'

const REPO = 'OthelloRhin/MHW_Icons_SVG'
const COMMIT = '242f7e883a6851e496ad01531ca499059230c57e'
const ROOT = join(import.meta.dirname, '../..')
const OUT = join(ROOT, 'src/assets/icons')

const WEAPON_DIR: Record<WeaponType, string> = {
  'great-sword': 'Great_Sword',
  'long-sword': 'Long_Sword',
  'sword-and-shield': 'Sword_&_Shield',
  'dual-blades': 'Dual_Blades',
  hammer: 'Hammer',
  'hunting-horn': 'Hunting_Horn',
  lance: 'Lance',
  gunlance: 'Gunlance',
  'switch-axe': 'Switch_Axe',
  'charge-blade': 'Charge_Blade',
  'insect-glaive': 'Insect_Glaive',
  'light-bowgun': 'Light_Bowgun',
  'heavy-bowgun': 'Heavy_Bowgun',
  bow: 'Bow',
}
// source "Torso" is the waist (belt) icon
const ARMOR_DIR = { head: 'Helm', chest: 'Chest', arms: 'Arms', waist: 'Torso', legs: 'Legs' } as const

/**
 * Skill `iconColor` (MHWorldData) -> source decoration color. Matched by eye from the rendered
 * icons; the source numbers its colors but the data only has names. Colors 12 and 19 unused.
 */
export const DECO_COLOR: Record<string, string> = {
  white: '00',
  red: '01',
  green: '02',
  blue: '03',
  gold: '04',
  violet: '05',
  cyan: '06',
  beige: '07',
  yellow: '09',
  gray: '10',
  'dark-beige': '11',
  'dark-green': '13',
  'dark-red': '14',
  'dark-blue': '15',
  'light-beige': '24',
  orange: '25',
  lime: '26',
}

function fetchSource(): string {
  const dir = join(ROOT, '.cache', `MHW_Icons_SVG-${COMMIT}`)
  if (existsSync(join(dir, 'SVG'))) return join(dir, 'SVG')
  mkdirSync(join(ROOT, '.cache'), { recursive: true })
  const tarball = `${dir}.tar.gz`
  execFileSync('curl', ['-sSfL', '-o', tarball, `https://codeload.github.com/${REPO}/tar.gz/${COMMIT}`], { stdio: 'inherit' })
  execFileSync('tar', ['-xzf', tarball, '-C', join(ROOT, '.cache')], { stdio: 'inherit' })
  rmSync(tarball)
  return join(dir, 'SVG')
}

const src = fetchSource()
let count = 0
const HEADER = `<!-- generated by scripts/icons from ${REPO}@${COMMIT.slice(0, 7)} (MIT), do not edit -->\n`

/** `to` is the icon id; writes `<id>.vue`. Size comes from the caller (no width/height). */
function copy(from: string, to: string) {
  const { data } = optimize(readFileSync(join(src, from), 'utf8'), {
    multipass: true,
    // ids are unused (no url(#) refs) and would collide when inlined many times
    plugins: ['preset-default', 'removeDimensions', 'removeXMLNS'],
  })
  const dest = join(OUT, `${to}.vue`)
  mkdirSync(dirname(dest), { recursive: true })
  writeFileSync(dest, `${HEADER}<template>\n  ${data}\n</template>\n`)
  count++
}

rmSync(OUT, { recursive: true, force: true })
const pad = (n: number) => String(n).padStart(2, '0')
for (let r = 1; r <= 12; r++) {
  for (const t of WEAPON_TYPES) {
    const d = WEAPON_DIR[t]
    // source typo: Charge Blade files use lowercase "rank"
    const file = t === 'charge-blade' ? `${d}_rank_${pad(r)}.svg` : `${d}_Rank_${pad(r)}.svg`
    copy(`Weapons/${d}/${file}`, `weapon/${t}/${r}`)
  }
  for (const [slot, d] of Object.entries(ARMOR_DIR)) copy(`Hunter/${d}/${d}_Rank_${pad(r)}.svg`, `armor/${slot}/${r}`)
  copy(`Hunter/Charm/Charm_Rank_${pad(r)}.svg`, `charm/${r}`)
}
for (const [color, n] of Object.entries(DECO_COLOR))
  for (let size = 1; size <= 4; size++) copy(`Decorations/Color_${n}_Rank_${size}.svg`, `deco/${color}/size-${size}`)
copyFileSync(join(src, '../LICENSE'), join(OUT, 'LICENSE-MHW_Icons_SVG'))
console.log(`copied ${count} icons from ${REPO}@${COMMIT.slice(0, 7)} to src/assets/icons`)
